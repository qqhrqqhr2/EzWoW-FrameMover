function ns:GetActiveLocaleCode()
    local savedDB = _G.EzWoW_FrameMoverDB
    local langCode = savedDB and savedDB.lang
    if not langCode or langCode == "Auto" then
        langCode = GetLocale and GetLocale() or "enUS"
    end
    if not self.Locales[langCode] then
        langCode = "enUS"
    end
    return langCode
end

function ns:L(key)
    local langCode = self:GetActiveLocaleCode()
    local targetTable = self.Locales[langCode] or self.Locales.enUS
    return (targetTable and targetTable[key]) or self.Locales.enUS[key] or key
end
